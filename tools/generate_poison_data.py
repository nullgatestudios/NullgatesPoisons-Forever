"""Builds Data/Poisons.lua from the Forever client's tables on wago.tools.

Every recipe on the rogue's Poisons skill line (40) that makes a poison: the poison item, its
required level, the weapon enchant its use spell applies (so the addon can tell which poison is
on a weapon), and the recipe's reagents. Poisons are grouped into types by name without the rank
numeral ("Instant Poison III" -> instant).

Usage:
  python tools/generate_poison_data.py [--build 1.60.1.70532] [--data DIR]
"""
import argparse
import csv
import io
import json
import os
import re
import sys
import urllib.request
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "NullgatesPoisons-Forever", "Data", "Poisons.lua")
TABLES = ("SpellName", "SpellEffect", "SpellReagents", "SkillLineAbility", "ItemSparse", "ItemEffect", "ItemXItemEffect")
POISONS_LINE = "40"
CREATE_ITEM = "24"
ENCHANT_EFFECTS = ("54", "360")   # temporary weapon enchant (360 is the Forever variant)
NUMERAL = re.compile(r"\s+(I|II|III|IV|V|VI|VII|VIII)$")


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "NullgatesPoisons-generator"})
    with urllib.request.urlopen(req, timeout=300) as resp:
        return resp.read().decode("utf-8")


def latest_build():
    return json.loads(fetch("https://wago.tools/api/builds/latest"))["wow_classic_beta"]["version"]


def load(name, build, data_dir):
    if data_dir:
        with open(os.path.join(data_dir, name + ".csv"), encoding="utf-8") as f:
            text = f.read()
    else:
        text = fetch("https://wago.tools/db2/%s/csv?build=%s" % (name, build))
    return list(csv.DictReader(io.StringIO(text)))


def to_int(value):
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return 0


def type_key(name):
    base = NUMERAL.sub("", name)
    if not base.endswith(" Poison"):
        return None, None
    return re.sub(r"[^a-z]", "", base[:-len(" Poison")].lower()), base


def build(t):
    names = {r["ID"]: r["Name_lang"] for r in t["SpellName"]}
    effects = defaultdict(list)
    for r in t["SpellEffect"]:
        effects[r["SpellID"]].append(r)
    reagents = {r["SpellID"]: r for r in t["SpellReagents"]}
    sparse = {r["ID"]: r for r in t["ItemSparse"]}
    item_effects = {r["ID"]: r for r in t["ItemEffect"]}
    use_spell = defaultdict(list)
    for r in t["ItemXItemEffect"]:
        e = item_effects.get(r["ItemEffectID"])
        if e:
            use_spell[r["ItemID"]].append(e["SpellID"])

    types, labels = defaultdict(list), {}
    for r in t["SkillLineAbility"]:
        if r["SkillLine"] != POISONS_LINE:
            continue
        recipe = r["Spell"]
        for e in effects.get(recipe, []):
            if e["Effect"] != CREATE_ITEM:
                continue
            item = e["EffectItemType"]
            s = sparse.get(item)
            if not s:
                continue
            key, label = type_key(s["Display_lang"])
            if not key:
                continue
            enchant = 0
            for spell in use_spell.get(item, []):
                for f in effects.get(spell, []):
                    if f["Effect"] in ENCHANT_EFFECTS and to_int(f["EffectMiscValue_0"]):
                        enchant = to_int(f["EffectMiscValue_0"])
            if not enchant:
                sys.exit("no weapon enchant found for " + s["Display_lang"])
            R = reagents.get(recipe, {})
            reag = [(to_int(R.get("Reagent_%d" % i)), to_int(R.get("ReagentCount_%d" % i))) for i in range(8)
                    if to_int(R.get("Reagent_%d" % i))]
            types[key].append({"item": to_int(item), "name": s["Display_lang"], "level": max(1, to_int(s["RequiredLevel"])),
                               "enchant": enchant, "recipe": to_int(recipe), "makes": max(1, to_int(e["EffectBasePointsF"])),
                               "reagents": reag})
            labels[key] = label
    for key in types:
        types[key].sort(key=lambda p: (p["level"], p["item"]))
    if "instant" not in types or "deadly" not in types:
        sys.exit("Instant and Deadly Poison are missing; the data looks wrong")
    return types, labels


ORDER = ["instant", "deadly", "crippling", "mindnumbing", "wound"]


def write(build_id, types, labels):
    keys = [k for k in ORDER if k in types] + sorted(k for k in types if k not in ORDER)
    lines = [
        "-- Generated by tools/generate_poison_data.py from the Forever client data. Do not edit by hand.",
        "local _, ns = ...",
        "",
        'ns.POISON_DATA_BUILD = "%s"' % build_id,
        "",
        "-- Poison types in display order, with their English names.",
        "ns.POISON_TYPES = { %s }" % ", ".join('"%s"' % k for k in keys),
        "ns.POISON_NAMES = {",
    ]
    for k in keys:
        lines.append('    %s = "%s",' % (k, labels[k]))
    lines += ["}", "", "-- Ranks per type, lowest level first: item, required level, the weapon enchant it applies,",
              "-- the recipe spell, how many one craft makes and the reagents { itemID, count }.", "ns.POISONS = {"]
    for k in keys:
        lines.append("    %s = {" % k)
        for p in types[k]:
            reag = ", ".join("{ %d, %d }" % r for r in p["reagents"])
            lines.append("        { item = %d, level = %d, enchant = %d, recipe = %d, makes = %d, reagents = { %s } }, -- %s" % (
                p["item"], p["level"], p["enchant"], p["recipe"], p["makes"], reag, p["name"]))
        lines.append("    },")
    lines.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return keys


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--build")
    parser.add_argument("--data")
    args = parser.parse_args()
    build_id = args.build or latest_build()
    types, labels = build({name: load(name, build_id, args.data) for name in TABLES})
    for k in write(build_id, types, labels):
        print("%-12s %s" % (k, ", ".join("%s (%d)" % (p["name"], p["level"]) for p in types[k])))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
